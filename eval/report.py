        f"- {v} of {n} plans passed the guardrail; generated Terraform passed `terraform validate` on "
        f"{a['tf_ok']} of {a['tf_n']}. It was validated, never deployed.",
        f"- On the {v} verified plans, mapping accuracy was {_pct(a['map_a_ver'])} against hand-written, "
        "human-reviewed ground truth.",
        "- Ran entirely on free tiers (Gemini free tier, GitHub Actions, Streamlit Community Cloud) with "
        "a response cache, RPM throttle and daily budget; evaluation replays from the cache with zero API calls.", "",
        "## What I must not say", "",
        "- That the agent is **more accurate than the baseline**. On service recall, risk coverage and "
        "all-apps mapping accuracy it was equal or worse once the unverified app is counted.",
        f"- \"{_pct(a['map_a_ver'])} mapping accuracy\" without \"on the {v} verified plans\".",
        "- That anything was **deployed** to Google Cloud, or that the Terraform is production-ready.",
        "- That the invented-resource win generalises: the baseline never saw `mapping.yaml`, the "
        "metric uses the same vocabulary the agent was told about, and n is small.",
        "- That the guardrail's retry loop rescued bad plans: every verified plan passed on the first draft.",
        f"- That the detector's {_pct(d1['macro_recall'])} recall is an independent result: SAM/CDK support was "
        "added after seeing these apps.",
        "- Any dollar or cost-saving figure. None was measured.", "",
        "## Suggested resume bullets (numbers filled from above)", "",
        "1. Built **MigrateLens**, a Google ADK and Gemini agent that plans AWS→Google Cloud migrations: "
        "inventories services with file:line evidence, maps them via a curated table and generates a "
        "migration plan, Terraform, Dockerfile and CI pipeline over an MCP tool layer.",
        f"2. Added a code-level evidence guardrail and an evaluation harness on **{n}** apps "
        f"({a['n_real']} public AWS samples + {a['n_synth']} synthetic): first-draft invented-resource rate "
        f"**{_pct(a['inv_a'])}** vs **{_pct(a['inv_b'])}** for a no-tools Gemini baseline; {v}/{n} plans verified; "
        f"generated Terraform validated on {a['tf_ok']}/{a['tf_n']}.",
        "3. Packaged the tools, guardrail, response cache, throttle and eval harness as reusable components "
        "with CI on GitHub Actions and a free-hosted Streamlit demo within Gemini free-tier limits.", "",
