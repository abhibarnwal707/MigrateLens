"""Build docs/RESULTS_SUMMARY.md from eval/results/*. Numbers are copied, never typed by hand."""

from __future__ import annotations

import json

from eval.metrics import EVAL_DIR, bootstrap_ci, mean

ROOT = EVAL_DIR.parent


def _load(mode: str) -> list[dict]:
    d = EVAL_DIR / "results" / mode
    return [json.loads(p.read_text()) for p in sorted(d.glob("*.json"))] if d.exists() else []


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def _ci(vals: list[float]) -> str:
    lo, hi = bootstrap_ci(vals)
    return f"{_pct(mean(vals))} [{_pct(lo)}, {_pct(hi)}]" if vals else "n/a"


METRICS = [
    ("Service precision", "service_precision"), ("Service recall", "service_recall"),
    ("Mapping accuracy", "mapping_accuracy"), ("Risk coverage", "risk_coverage"),
    ("Invented-resource rate (first draft)", "invented_rate"),
]  # fmt: skip


def build() -> str:
    agent, base = _load("agent"), _load("baseline")
    det = {k: json.loads((EVAL_DIR / "results" / f"detector_{k}.json").read_text())
           for k in ("before_sam_cdk", "after_sam_cdk")
           if (EVAL_DIR / "results" / f"detector_{k}.json").exists()}  # fmt: skip
    L = [
        "# Results summary",
        "",
        "Generated by `make report` from `eval/results/`. Do not edit by hand.",
        "",
    ]
    reviewed = sum(1 for r in agent + base if r.get("human_reviewed"))
    L += [f"**Ground truth review status:** {reviewed} of {len(agent) + len(base)} scored rows use "
          "human-reviewed truth. Unreviewed truth means these numbers are provisional.", ""]  # fmt: skip

    from eval.metrics import app_names

    done = {m: {r["app"] for r in rows} for m, rows in (("agent", agent), ("baseline", base))}
    L += ["## Run status", ""]
    for m in ("agent", "baseline"):
        missing = [a for a in app_names() if a not in done[m]]
        L.append(f"- {m}: {len(done[m])} of {len(app_names())} apps recorded"
                 + (f"; NOT yet recorded: {', '.join(missing)}" if missing else ""))  # fmt: skip
    L += ["- Free-tier daily budget limits how many live calls fit per day; recording resumes from "
          "the cache (`python -m eval.run_eval --record`).", ""]  # fmt: skip

    L += ["## 1. Deterministic detector (no LLM, no API)", "",
          "Reproduce: `uv run python -m eval.detector_eval`", "",
          "| Detector version | Macro precision | Macro recall | Micro precision | Micro recall |",
          "|---|---|---|---|---|"]  # fmt: skip
    for k, label in (("before_sam_cdk", "Before SAM/CDK support"),
                     ("after_sam_cdk", "After SAM/CDK support (partly tuned on these apps)")):  # fmt: skip
        if k in det:
            d = det[k]
            L.append(f"| {label} | {_pct(d['macro_precision'])} | {_pct(d['macro_recall'])} | "
                     f"{_pct(d['micro_precision'])} | {_pct(d['micro_recall'])} |")  # fmt: skip
    L.append("")

    L += ["## 2. Agent vs no-tools baseline", "",
          f"Apps scored: agent n={len(agent)}, baseline n={len(base)}. "
          "Values are means over apps with 95% bootstrap intervals (small n: wide).", "",
          "Reproduce (zero API calls, from the committed cache): `make eval && make baseline && "
          "make report`", "",
          "| Metric | Agent | Baseline |", "|---|---|---|"]  # fmt: skip
    for label, key in METRICS:
        L.append(f"| {label} | {_ci([r[key] for r in agent])} | {_ci([r[key] for r in base])} |")
    ver = [r["verdict"] == "verified" for r in agent]
    L.append(f"| Verified-plan rate (guardrail passed within 2 retries) | "
             f"{_pct(sum(ver) / len(ver)) if ver else 'n/a'} ({sum(ver)}/{len(ver)}) | n/a (no guardrail) |")  # fmt: skip
    tf = [r["terraform_ok"] for r in agent if r.get("terraform_ok") is not None]
    L.append(f"| Terraform validate pass rate | "
             f"{_pct(sum(tf) / len(tf)) if tf else 'n/a'} ({sum(tf)}/{len(tf)}) | n/a (no artifacts) |")  # fmt: skip
    for label, key in (("Mean tokens", "tokens"), ("Mean LLM calls", "llm_calls"),
                       ("Mean retries", "retries")):  # fmt: skip
        L.append(f"| {label} | {mean([r[key] for r in agent]):.1f} | "
                 f"{mean([r[key] for r in base]):.1f} |" if agent and base else f"| {label} | n/a | n/a |")  # fmt: skip
    wall = [r["wall_seconds"] for r in agent if r.get("wall_seconds")]
    wallb = [r["wall_seconds"] for r in base if r.get("wall_seconds")]
    L.append(f"| Mean wall time (s, live run, throttled to the free-tier RPM) | "
             f"{mean(wall):.1f} | {mean(wallb):.1f} |" if wall and wallb else
             "| Mean wall time (s) | n/a | n/a |")  # fmt: skip
    L.append("")

    L += ["## 3. Per-app rows", "",
          "| App | Mode | Verdict | Svc P | Svc R | Map | Risk | Invented | Retries |",
          "|---|---|---|---|---|---|---|---|---|"]  # fmt: skip
    for r in agent + base:
        L.append(f"| {r['app']} | {r['mode']} | {r.get('verdict', '-')} | "
                 f"{_pct(r['service_precision'])} | {_pct(r['service_recall'])} | "
                 f"{_pct(r['mapping_accuracy'])} | {_pct(r['risk_coverage'])} | "
                 f"{_pct(r['invented_rate'])} | {r['retries']} |")  # fmt: skip
    L.append("")
    L += ["## 4. How to read this (limitations)", "",
          "- Small sample (7 apps, 1 synthetic); intervals are wide; differences may be noise.",
          "- Risk coverage is a fixed keyword rubric, not an LLM judge; it can miss paraphrases.",
          "- Invented-resource rate counts guardrail violations in the FIRST draft, before retries.",
          "  The baseline has no mapping table, so Google Cloud products outside `mapping.yaml` "
          "count against it by design.",  # fmt: skip
          "- Terraform pass rate measures the templated generator, not the LLM.",
          "- A run that ends `could_not_verify` produces no plan and is scored as zero precision and "
          "recall. The guardrail only accepts AWS services present in the detector inventory, so a "
          "repo that really uses services outside `mapping.yaml` (for example EC2) cannot get a "
          "verified plan; see the per-app rows and `eval/results/agent/<app>.json` rejections.",  # fmt: skip
          "- The guardrail's retry loop did not trigger on any app that passed; those plans were "
          "clean on the first draft, so its recovery value is not demonstrated by these runs.",  # fmt: skip
          "- Scoring was adjusted once, after the first baseline run, because two artifacts showed up: "
          "lines that negate usage ('RDS is absent') are not counted as usage claims, and bare "
          "IAM is neutral in precision, recall and mapping. The same scorer applies to both modes.",  # fmt: skip
          "- Known scorer limit: 'CloudWatch Events' (an alias of EventBridge) is read as CloudWatch.",
          "- The service precision/recall rows score the plan text, so they measure what the model "
          "wrote, not what the detector found.",  # fmt: skip
          "- Free-tier Gemini, one model; nothing was deployed to Google Cloud.", ""]  # fmt: skip
    return "\n".join(L)


def main() -> None:
    out = ROOT / "docs" / "RESULTS_SUMMARY.md"
    out.write_text(build())
    print("wrote", out)


if __name__ == "__main__":
    main()
